import { writeFile } from "node:fs/promises";
import { scenarios } from "./scenarios.js";
import { countBroken, FAULT_RATE } from "./sweep.js";
import { judge, makeWorld } from "./harness.js";

const TRIALS = Number(process.env.TRIALS ?? 40);

interface Row {
  name: string;
  fault: string;
  naive: string;
  naiveVerdict: string;
  hardened: string;
  hardenedVerdict: string;
}

const rows: Row[] = [];
for (const s of scenarios) {
  const naive = await s.run("baseline");
  const hardened = await s.run("hardened");
  rows.push({
    name: s.name,
    fault: s.fault,
    naive: `${naive.movedCents} / ${naive.db.succeededCents} (want ${naive.expectedMovedCents})`,
    naiveVerdict: naive.violations.length ? "FAIL: " + naive.violations[0] : "ok",
    hardened: `${hardened.movedCents} / ${hardened.db.succeededCents} (want ${hardened.expectedMovedCents})`,
    hardenedVerdict: hardened.violations.length ? "FAIL: " + hardened.violations[0] : "ok",
  });
}

const naiveBroken = await countBroken("baseline", TRIALS);
const hardenedBroken = await countBroken("hardened", TRIALS);

// Mutation checks: remove one defence at a time, expect the matching scenario to break.
const wKey = await makeWorld("hardened", 10_000, "no-idempotency-key");
wKey.provider.inject("timeout_after_success");
await wKey.refund({ requestKey: "k1", amountCents: 4000 });
await wKey.restart();
const mKey = await judge(wKey, 4000);

const wGuard = await makeWorld("hardened", 10_000, "no-balance-guard");
await Promise.all([
  wGuard.refund({ requestKey: "k1", amountCents: 7000 }),
  wGuard.refund({ requestKey: "k2", amountCents: 7000 }),
]);
await wGuard.restart();
const mGuard = await judge(wGuard, 7000);

const table = [
  "| scenario | fault injected | naive: moved / recorded | naive verdict | hardened: moved / recorded | hardened verdict |",
  "| --- | --- | --- | --- | --- | --- |",
  ...rows.map(
    (r) =>
      `| ${r.name} | ${r.fault} | ${r.naive} | ${r.naiveVerdict} | ${r.hardened} | ${r.hardenedVerdict} |`,
  ),
].join("\n");

const md = `# Report: refund-exactly-once

Generated by \`npm run report\` from a real run of this repo. CI regenerates it and fails if the checked-in copy is stale.

The provider is a fake written for this repo. No real payments, keys or network calls; nothing here is modelled on any particular company's product or API.

## Setup

- runtime: Node 20 or newer (CI runs 20 and 22), tsx, node:test
- database: PGlite (Postgres compiled to WASM), a fresh in-memory instance per run
- variants: \`baseline\` (naive tool execution) vs \`hardened\` (exactly-once tool execution)
- random sweep: ${TRIALS} seeds per variant, 8 tool calls over 5 request keys per run, per-call fault rate ${FAULT_RATE} (timeouts, 5xx, lost responses, crashes), retry budget 3 attempts per call

## Scenarios

Amounts are cents. "moved / recorded" is the provider total vs what the database recorded for the payment.

${table}

## Random sweep

- hardened: ${hardenedBroken}/${TRIALS} runs violated an invariant (over-refund, provider vs database drift, payment-total drift, or a refund stuck pending)
- naive: ${naiveBroken}/${TRIALS} runs violated the same invariants

## Mutation checks

Each defence was removed one at a time to confirm it is load-bearing:

- without the idempotency key: timeout-after-success moved ${mKey.movedCents} cents where ${mKey.expectedMovedCents} was intended ("${mKey.violations[0] ?? "no violation - BUG"}")
- without the balance guard: concurrent approvals moved ${mGuard.movedCents} cents on a 10000 payment ("${mGuard.violations[0] ?? "no violation - BUG"}")

## Limits

- The fake provider is a simplified model: idempotency keys are remembered forever and a replay returns the first result. Real providers differ.
- PGlite is a single connection, so the concurrency tests interleave async operations rather than using parallel database sessions. The hardened code is written for real Postgres (unique index, ON CONFLICT, atomic conditional update), but this repo does not test parallel sessions.
- One payment, partial refunds, one currency. No auth, no webhooks, no provider-side failure after acceptance.
- The ${FAULT_RATE} fault rate is chosen to exercise the failure modes, not measured from any production system.
- It is a demonstration, not a payments library.
`;

await writeFile(new URL("../REPORT.md", import.meta.url), md);
console.log(
  `wrote REPORT.md (node ${process.version}, ${TRIALS} seeds: naive broke ${naiveBroken}, hardened broke ${hardenedBroken})`,
);
